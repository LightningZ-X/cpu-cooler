const assets = {};
const mime = {
  ".png": "image/png",
  ".webp": "image/webp",
  ".svg": "image/svg+xml",
};
async function walk(directory) {
  for (const item of await fs.readdir(path.join(root, directory), {
    withFileTypes: true,
  })) {
    const name = `${directory}/${item.name}`;
    if (item.isDirectory()) await walk(name);
    else if (mime[path.extname(name)])
      assets[name] =
        `data:${mime[path.extname(name)]};base64,${(await fs.readFile(path.join(root, name))).toString("base64")}`;
  }
}
await walk("assets");
function inlineAssets(html) {
  return html.replace(
    /\b(src|href|data-video)="(assets\/[^"?#]+)"/g,
    (attribute, kind, name) => {
      if (kind === "data-video" && name === bootVideo[1])
        return `data-video="${bootVideoData}"`;
      if (!assets[name]) throw new Error(`Missing asset: ${name}`);
      return `${kind}="${assets[name]}"`;
    },
  );
}
