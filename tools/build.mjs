// A deliberately limited linker for this project's named local imports. Unsupported
// module syntax fails the build; no eval, runtime loader or browser module fetch is used.
export async function bundle(entry) {
  const modules = new Map();
  const visiting = new Set();
  async function visit(file) {
    if (visiting.has(file)) throw new Error(`Circular import: ${file}`);
    if (modules.has(file)) return;
    visiting.add(file);
    let source = await read(file);
    const imports = [
      ...source.matchAll(
        /^import\s+(?:\{([\s\S]*?)\}\s+from\s+)?["']([^"']+)["'];/gm,
      ),
    ];
    for (const match of imports) {
      if (!match[2].startsWith("./"))
        throw new Error(`Unsupported import in ${file}`);
      const dependency = path.posix.normalize(
        path.posix.join(path.posix.dirname(file), match[2]),
      );
      await visit(dependency);
      const names = match[1]?.trim().replace(/\bas\b/g, ":");
      source = source.replace(
        match[0],
        names
          ? `const {${names}} = modules[${JSON.stringify(dependency)}];`
          : "",
      );
    }
    const exports = [
      ...source.matchAll(
        /^export\s+(?:async\s+)?(?:function|const|let|class)\s+(\w+)/gm,
      ),
    ].map((match) => match[1]);
    source = source.replace(
      /^export\s+(?=(?:async\s+)?(?:function|const|let|class)\s)/gm,
      "",
    );
    if (/\bimport\s*(?:\(|\.)/.test(source))
      throw new Error(`Runtime imports are not supported: ${file}`);
    // vm.Script rejects residual import/export/import.meta, unsupported aliases, etc.
    new vm.Script(`(()=>{${source}\n})()`, { filename: file });
    modules.set(
      file,
      `modules[${JSON.stringify(file)}] = (()=>{\n${source}\nreturn {${exports.join(",")}};\n})();`,
    );
    visiting.delete(file);
  }
  await visit(entry);
  return `/* Generated by tools/build.mjs. Edit js source modules. */\n(()=>{\n"use strict";\nconst modules = Object.create(null);\n${[...modules.values()].join("\n")}\n})();`;
}
